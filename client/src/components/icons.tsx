import type { ReactNode } from "react";

/**
 * Small inline SVG icons (Feather-style, 24x24 viewBox, stroked). Color is
 * inherited via `currentColor`, so set `color` on the parent/button.
 */
function Icon({ size = 16, children }: { size?: number; children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      style={{ display: "block" }}
    >
      {children}
    </svg>
  );
}

